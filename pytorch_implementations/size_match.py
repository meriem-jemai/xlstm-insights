"""
n: new file. Finds the hidden size for each model so that all models have (about) the same
number of parameters, and writes scripts/run_sized.ps1 with the training commands.

Why this is needed:
    At the same hidden size (256), the models have very different sizes:
        LSTM   573k parameters
        mLSTM  313k parameters
        xLSTM  2,286k parameters
    A bigger model can store more, so it might win just because it is bigger.
    For a fair comparison every model gets the same "budget": the size of the LSTM with hidden 256.

How it works:
    1. target = number of parameters of the LSTM with hidden 256 (about 573k)
    2. for each model, try hidden sizes 16, 20, 24, ... and count the parameters each time
    3. keep the hidden size whose count is closest to the target
    4. write one training command per model into scripts/run_sized.ps1

Result (Shakespeare):
        LSTM   hidden 256 -> 573k
        sLSTM  hidden 320 -> 572k
        mLSTM  hidden 356 -> 576k
        xLSTM  hidden 128 -> 588k
    If one model wins now, it is because of its design, not its size.

Usage:
    python size_match.py                 # target = LSTM with hidden 256
    python size_match.py --target 600000 # or any other parameter budget
"""
import argparse

from training.data import prepare_dataset
from models import build_model

# The runs that should be size-matched: (model, mlstm_variant, xlstm block order, datasets).
# The vocabulary size differs per dataset (the embedding and output layer depend on it),
# so the matching hidden size is computed separately for each dataset.
RUNS = [
    ("slstm", "base", "s,m", ["shakespeare.txt"]),
    ("mlstm", "base", "s,m", ["shakespeare.txt", "copy_train.txt", "dyck_train.txt"]),
    ("mlstm", "separate", "s,m", ["shakespeare.txt", "copy_train.txt", "dyck_train.txt"]),
    ("mlstm", "global", "s,m", ["shakespeare.txt", "copy_train.txt", "dyck_train.txt"]),
    ("xlstm", "base", "s,m", ["shakespeare.txt"]),
]


def count(model):
    """Total number of trainable numbers (weights and biases) in the model."""
    return sum(p.numel() for p in model.parameters())


def best_hidden(name, variant, blocks, vocab, target, emb, heads):
    """Hidden size (multiple of the number of heads) whose parameter count is closest to target."""
    best = None  # (hidden size, parameter count) closest to the target so far
    # the hidden size must be divisible by the number of heads, so we step in multiples of heads
    for hidden in range(heads * 4, 1025, heads):
        n = count(build_model(name, vocab, emb, hidden, heads, blocks, variant))
        if best is None or abs(n - target) < abs(best[1] - target):
            best = (hidden, n)
        if n > target * 1.2:  # parameters only grow with the hidden size, so we can stop
            break
    return best


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--target", type=int, default=None, help="parameter budget (default: LSTM, hidden 256)")
    ap.add_argument("--embedding", type=int, default=128)
    ap.add_argument("--heads", type=int, default=4)
    args = ap.parse_args()

    # vocabulary size of each dataset (number of different characters)
    vocabs = {}
    for _, _, _, datasets in RUNS:
        for d in datasets:
            if d not in vocabs:
                vocabs[d] = prepare_dataset(d, device="cpu")[2]

    # the PowerShell script first goes back to pytorch_implementations, so it can be started from anywhere
    lines = ["# n: generated by size_match.py, all models with about the same number of parameters",
             'Set-Location (Join-Path $PSScriptRoot "..")  # run from pytorch_implementations',
             '$py = "..\\.venv\\Scripts\\python"', ""]
    for name, variant, blocks, datasets in RUNS:
        for d in datasets:
            vocab = vocabs[d]
            # the budget: the LSTM with hidden 256 on this dataset (or the --target given by the user)
            target = args.target or count(build_model("lstm", vocab, args.embedding, 256, args.heads))
            hidden, n = best_hidden(name, variant, blocks, vocab, target, args.embedding, args.heads)
            label = name if name != "mlstm" else f"mlstm ({variant})"
            done = hidden == 256  # runs with hidden 256 were already trained by run_all.ps1
            print(f"{d:16s} {label:18s} hidden {hidden:4d} -> {n:>9,} params (target {target:,})"
                  + ("  already trained" if done else ""))
            if done:
                continue
            # one training command for this model and dataset
            cmd = f"& $py train.py --data {d} --model {name} --hidden {hidden}"
            if name == "mlstm":
                cmd += f" --mlstm_variant {variant}"
            if name == "xlstm":
                cmd += f" --blocks {blocks}"
            lines.append(cmd)

    with open("scripts/run_sized.ps1", "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("\nWrote scripts/run_sized.ps1")


if __name__ == "__main__":
    main()
